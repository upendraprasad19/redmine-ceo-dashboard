#!/usr/bin/env node
/**
 * check-audit-readers-writers.js
 * Gate: Validates table usage audit passes (no phantom writes, no dead tables).
 * Extends lib/table-audit.js with YAML output option.
 *
 * Usage:
 *   node scripts/check-audit-readers-writers.js              # Console output
 *   node scripts/check-audit-readers-writers.js --format yaml  # YAML output for SoT Registry
 */
const { config } = require('dotenv')
config({ path: '.env.local' })

const { getDb } = require('../lib/db')
const { auditTableUsage } = require('../lib/table-audit')

function toYaml(report) {
  const lines = [
    '# Auto-generated by: scripts/check-audit-readers-writers.js --format yaml',
    `# Generated at: ${new Date().toISOString()}`,
    '',
    'tables:',
  ]

  const allTables = new Set([...Object.keys(report.reads), ...Object.keys(report.writes)])
  for (const table of [...allTables].sort()) {
    lines.push(`  ${table}:`)
    const readers = report.reads[table] || []
    const writers = report.writes[table] || []
    if (readers.length > 0) {
      lines.push('    readers:')
      for (const r of readers) {
        lines.push(`      - "${r}"`)
      }
    }
    if (writers.length > 0) {
      lines.push('    writers:')
      for (const w of writers) {
        lines.push(`      - "${w}"`)
      }
    }
  }

  if (report.deadTables.length > 0) {
    lines.push('')
    lines.push('# Dead tables (in DB but not referenced in code):')
    for (const t of report.deadTables) {
      lines.push(`#   - ${t}`)
    }
  }

  return lines.join('\n')
}

async function main() {
  const sql = getDb()
  const report = await auditTableUsage(sql)
  const isYaml = process.argv.includes('--format', 'yaml') || process.argv.includes('--format=yaml')

  if (isYaml) {
    console.log(toYaml(report))
  } else {
    console.log('=== Readers/Writers Audit ===\n')
    console.log(`API files scanned: ${report.totalFiles}`)
    console.log(`DB tables: ${report.totalDbTables}`)
    console.log(`Tables referenced in code: ${report.totalCodeTables}\n`)

    if (!report.ok && report.error) {
      console.error(`ERROR: ${report.error}`)
      process.exit(1)
    }

    console.log('Table Usage:')
    console.log('-'.repeat(60))
    for (const table of Object.keys({ ...report.reads, ...report.writes }).sort()) {
      const readers = report.reads[table]
      const writers = report.writes[table]
      const isDead = report.deadTables.includes(table)
      const isReadOnly = report.readOnlyTables.includes(table)
      const status = isDead ? ' [DEAD]' : isReadOnly ? ' [READ-ONLY]' : ''
      console.log(`  ${table}${status}`)
      if (readers) console.log(`    Reads:  ${readers.join(', ')}`)
      if (writers) console.log(`    Writes: ${writers.join(', ')}`)
    }
  }

  if (report.phantomWrites.length > 0) {
    console.error('\nPHANTOM WRITES (code references table not in DB):')
    for (const t of report.phantomWrites) console.error(`  - ${t}`)
    process.exit(1)
  }

  process.exit(0)
}

main().catch((err) => {
  console.error('Audit failed:', err.message)
  process.exit(1)
})
